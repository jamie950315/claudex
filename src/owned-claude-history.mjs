// CLI 2.1.281 repairs a resumed no-query user tail with this zero-usage
// placeholder before persisting the next input. It is not an authored reply.
// Recognize it only immediately after an authenticated imported packet.
function noQueryReceipt(message) {
  return message.role === 'assistant' && message.model === '<synthetic>' && message.stop_reason === 'stop_sequence'
    && message.content?.length === 1 && message.content[0].type === 'text' && message.content[0].text === 'No response requested.'
    && message.usage?.input_tokens === 0 && message.usage?.output_tokens === 0
    && Object.values(message.usage).every(value => value === 0);
}

const messageKey = message => {
  const time = Date.parse(message.timestamp);
  const timestamp = Number.isFinite(time) ? new Date(time).toISOString() : message.timestamp ?? '';
  return `${timestamp}:${fingerprint({ messages: [message] })}`;
};

const CLEAR_CAVEAT = '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>';
const CLEAR_COMMAND = '<command-name>/clear</command-name>\n            <command-message>clear</command-message>\n            <command-args></command-args>';

// Bound to one synchronous read of an immutable transcript string. Exact
// native content, not operation IDs or archive references, identifies reuse.
// Decoded results never escape until all prefix and parent checks finish, and
// no entry survives into another snapshot or resolver lifetime.
function packetDecoder({ conversationId, sessionId, key, resolveArchive }) {
  const packets = new Map();
  return content => {
    const identity = Array.isArray(content) ? content.at(-1)?.text : undefined;
    const previous = packets.get(identity);
    // The footer only selects a candidate. Equality includes every native
    // block, field, and value, independent of JSON object property order.
    if (previous && isDeepStrictEqual(previous.content, content)) return previous.packet;
    const packet = decodeContextPacket({ content, conversationId, targetSessionId: sessionId, key, resolveArchive });
    if (packet) packets.set(identity, { content, packet });
    return packet;
  };
}

function resetTransportKeys(text, native, options, decodePacket) {
  const proof = options.resetBootstrap;
  if (!proof) return new Set();
  if (proof.sessionId !== options.sessionId || proof.receipt?.sessionId !== options.sessionId
      || proof.receipt.localCommand !== 'clear' || proof.receipt.numTurns !== 0 || proof.receipt.apiMs !== 0 || proof.receipt.cost !== 0)
    throw new Error('Owned reset bootstrap lacks a verified native no-query receipt.');
  const rows = text.split('\n').filter(Boolean).map(JSON.parse);
  const index = rows.findIndex(row => row.uuid === proof.bootstrapUuid);
  const bootstrap = rows[index];
  if (index < 0 || bootstrap.type !== 'user' || bootstrap.sessionId !== options.sessionId
      || bootstrap.promptSource !== 'sdk' || bootstrap.queueTranscriptOnly !== true)
    throw new Error('Owned reset bootstrap is missing its native restoring input.');
  const packet = decodePacket(bootstrap.message?.content);
  if (!packet?.archive || packet.sourceSide !== 'codex' || packet.previousDigest !== null || packet.operationId !== proof.operationId)
    throw new Error('Owned reset bootstrap does not authenticate the complete archived checkpoint.');
  const prefix = rows.slice(0, index).filter(row => row.uuid && !row.isSidechain && ['user', 'assistant', 'system'].includes(row.type));
  const [caveat, command, output] = prefix;
  if (prefix.length !== 3 || prefix.some(row => row.sessionId !== options.sessionId
      || !runtimeVersionPermitted(row.version, '2.1.281', options.versionPolicy) || row.cwd !== bootstrap.cwd)
      || caveat.type !== 'user' || caveat.isMeta !== true || caveat.parentUuid !== null || caveat.queueTranscriptOnly !== true || caveat.message?.content !== CLEAR_CAVEAT
      || command.type !== 'user' || command.isMeta === true || command.parentUuid !== caveat.uuid || command.queueTranscriptOnly !== true || command.message?.content !== CLEAR_COMMAND
      || output.type !== 'system' || output.subtype !== 'local_command' || output.parentUuid !== command.uuid
      || output.content !== '<local-command-stdout></local-command-stdout>' || bootstrap.parentUuid !== output.uuid)
    throw new Error('Native reset prefix contains unsupported or concurrent history; nothing was excluded.');
  const transported = native.messages.filter(message => message.role === 'user' && message.content.length === 1
    && (message.content[0].type === 'tool_use' && message.content[0].id === command.uuid
      && message.content[0].tool?.name === 'Command' && message.content[0].tool.command === '/clear'
      || message.content[0].type === 'tool_result' && message.content[0].tool_use_id === command.uuid && message.content[0].content === ''));
  if (transported.length !== 2) throw new Error('Native reset command has an ambiguous codec identity.');
  return new Set(transported.map(messageKey));
}

function nativeImageAnnotationKeys(text, native, { sessionId, versionPolicy }, decodePacket) {
  const rows = text.split('\n').filter(Boolean).map(JSON.parse);
  const byId = new Map(rows.filter(row => row.uuid).map(row => [row.uuid, row]));
  const excluded = new Set();
  for (const row of rows) {
    if (row.type !== 'user' || row.isMeta !== true || row.isSidechain || row.sessionId !== sessionId
        || !runtimeVersionPermitted(row.version, '2.1.281', versionPolicy)) continue;
    const parent = byId.get(row.parentUuid);
    if (parent?.type !== 'user' || parent.sessionId !== sessionId || parent.promptSource !== 'sdk' || parent.queueTranscriptOnly !== true
        || !row.promptId || row.promptId !== parent.promptId || row.timestamp !== parent.timestamp || row.cwd !== parent.cwd
        || !Array.isArray(parent.imagePasteIds) || !parent.imagePasteIds.length
        || new Set(parent.imagePasteIds).size !== parent.imagePasteIds.length
        || parent.imagePasteIds.some(id => !Number.isSafeInteger(id) || id < 0)) continue;
    const packet = decodePacket(parent.message?.content);
    if (!packet || packet.sourceSide !== 'codex') continue;
    const images = parent.message.content.filter(block => block.type === 'image');
    const content = row.message?.content;
    if (images.length !== parent.imagePasteIds.length || !Array.isArray(content) || !content.length
        || content.some(block => block.type !== 'text' || typeof block.text !== 'string')) continue;
    // The pinned CLI emits one text block per image for multi-image inputs.
    // Also retain the previously supported single-block newline representation.
    // Do not flatten arbitrary block/line combinations or discard extra text.
    const lines = content.length === 1 ? content[0].text.split('\n') : content.map(block => block.text);
    if (lines.length !== images.length || typeof parent.cwd !== 'string') continue;
    const encodedProject = parent.cwd.replace(/[^a-zA-Z0-9]/g, '-');
    const valid = lines.every((line, index) => {
      const match = /^\[Image: source: (\/[^\r\n]+?)(?:, original [1-9]\d*x[1-9]\d*, displayed at [1-9]\d*x[1-9]\d*\. Multiply coordinates by \d+\.\d{2} to map to original image\.)?\]$/.exec(line);
      const extensions = { 'image/png': ['png'], 'image/jpeg': ['jpg', 'jpeg'], 'image/gif': ['gif'], 'image/webp': ['webp'] }[images[index].source?.media_type];
      return Boolean(match && extensions?.some(extension => match[1].endsWith(`/${encodedProject}/${sessionId}/images/${parent.imagePasteIds[index]}.${extension}`)));
    });
    if (!valid) continue;
    const identity = messageKey({ role: 'user', content: row.message.content, timestamp: row.timestamp });
    if (excluded.has(identity) || native.messages.filter(message => messageKey(message) === identity).length !== 1) {
      throw new Error('Native image annotation identity is ambiguous; no metadata was discarded.');
    }
    excluded.add(identity);
  }
  return excluded;
}

/** A completed native assistant turn or an authenticated no-query packet forms
 * a publication boundary. A newer unfinished user turn is deliberately kept
 * local until it finishes, rather than blocking earlier completed work.
 */
function completedPrefix(options, decodePacket) {
  const { text, key } = options;
  let offset = 0, cutoff = 0;
  for (const line of text.split('\n')) {
    offset += line.length + 1;
    if (!line) continue;
    let row;
    try { row = JSON.parse(line); } catch { throw new Error('Malformed Claude history; source was left unchanged.'); }
    if (row.isSidechain) continue;
    if (row.type === 'assistant' && ['end_turn', 'stop_sequence'].includes(row.message?.stop_reason)) cutoff = offset;
    if (key && row.type === 'user') {
      const packet = decodePacket(row.message?.content);
      if (packet) cutoff = offset;
    }
  }
  if (!cutoff) throw new Error('Wait for a complete assistant turn or verified synchronized checkpoint.');
  const tail = text.slice(cutoff).split('\n').filter(Boolean).map(JSON.parse).filter(row =>
    !row.isSidechain && (row.type === 'user' || row.type === 'assistant'));
  if (key && tail.length === 1 && tail[0].type === 'user' && tail[0].isMeta === true
    && Array.isArray(tail[0].message?.content) && tail[0].message.content.length > 0
    && tail[0].message.content.every(block => block.type === 'text' && typeof block.text === 'string'
      && block.text.startsWith('[Image: source: '))) {
    // The pinned CLI adds one image-source sidecar after a no-query packet.
    // It is complete only after the FULL native graph and authenticated parent
    // prove that this sole trailing message is exactly that inert annotation.
    const validated = decodeOwnedNative(options, decodePacket);
    const imageAnnotations = nativeImageAnnotationKeys(text, validated.native,
      { sessionId: options.sessionId, versionPolicy: validated.versionPolicy }, decodePacket);
    if (imageAnnotations.has(messageKey({ role: 'user', content: tail[0].message.content, timestamp: tail[0].timestamp })))
      return { text, incompleteTail: false, validated: { ...validated, imageAnnotations } };
  }
  return { text: text.slice(0, cutoff), incompleteTail: tail.length > 0 };
}

export function completedClaudePrefix(options) {
  const { text, incompleteTail } = completedPrefix(options, packetDecoder(options));
  return { text, incompleteTail };
}

function decodeOwnedNative({ text, sessionId, versionPolicy = 'strict' }, decodePacket) {
  versionPolicy = normalizeVersionPolicy(versionPolicy);
  const rows = text.split('\n').filter(Boolean).map(JSON.parse);
  const firstCompaction = rows.findIndex(row => !row.isSidechain && row.type === 'system' && row.subtype === 'compact_boundary');
  if (firstCompaction >= 0 && !rows.slice(0, firstCompaction).some(row => !row.isSidechain && row.type === 'user' && decodePacket(row.message?.content)))
    throw new Error('Owned Claude compaction requires its authenticated earlier checkpoint.');
  const native = decodeClaude(text, { preserveCompactionHistory: true, authenticatePreservedPacket(row, boundary, summary) {
    if (row.sessionId !== sessionId || row.sessionId !== boundary.sessionId || row.cwd !== boundary.cwd
      || row.version !== boundary.version || row.version !== summary.version
      || !runtimeVersionPermitted(row.version, '2.1.281', versionPolicy)) return false;
    const packet = decodePacket(row.message?.content);
    return packet?.sourceSide === 'codex';
  } });
  if (native.meta.id !== sessionId) throw new Error('Owned Claude history has a different native session identity.');
  return { native, versionPolicy };
}

/** Recover logical conversation history without mistaking imports for new turns.
 * The native SDK remains the only writer. Callers must snapshot the source and
 * require an idle owner before using this view as a completed source checkpoint.
 */
function ownedClaudeHistory(options, decodePacket, validated) {
  const { text, conversationId, sessionId, resetBootstrap } = options;
  const { native, versionPolicy } = validated ?? decodeOwnedNative(options, decodePacket);
  // Validate the full native parent graph first. Then exclude only the known
  // CLI image-source format tied to an authenticated no-query packet. Warn
  // policy relaxes version tags, not the sidecar's provenance or format.
  // The sidecar stays in the native transcript and is not an authored turn.
  const imageAnnotations = validated?.imageAnnotations ?? nativeImageAnnotationKeys(text, native, { sessionId, versionPolicy }, decodePacket);
  const resetAnnotations = resetTransportKeys(text, native, { sessionId, resetBootstrap, versionPolicy }, decodePacket);
  const messages = [];
  const prefixFingerprint = incrementalFingerprint();
  const append = additions => {
    // All additions come from this synchronous decode's private native parse
    // or packet canonicalization. Nothing mutates an appended message before
    // the final independent full fingerprint below.
    prefixFingerprint.append(additions);
    messages.push(...additions);
  };
  const operations = new Set();
  let importedPackets = 0;
  let followsPacket = false;
  for (const message of native.messages) {
    if (imageAnnotations.has(messageKey(message)) || resetAnnotations.has(messageKey(message))) continue;
    const packet = message.role === 'user' ? decodePacket(message.content) : null;
    if (!packet) {
      const receipt = followsPacket && noQueryReceipt(message);
      followsPacket = false;
      if (!receipt) append(portableMessages([message]));
      continue;
    }
    if (packet.sourceSide !== 'codex') throw new Error('Owned Claude history contains a packet from the wrong source side.');
    if (operations.has(packet.operationId)) throw new Error('Owned Claude history contains a repeated synchronization operation.');
    const previous = messages.length ? prefixFingerprint.digest() : null;
    if (packet.previousDigest !== previous) throw new Error('Owned Claude history does not match the synchronized prefix; no branch was selected.');
    if (packet.historyPrefixCount !== undefined && (packet.historyPrefixCount !== messages.length
      || fingerprint({ messages: packet.messages }, packet.historyPrefixCount) !== previous))
      throw new Error('Owned Claude image refresh does not match the complete synchronized prefix; no history was duplicated.');
    operations.add(packet.operationId);
    append(packet.historyPrefixCount === undefined ? packet.messages : packet.messages.slice(packet.historyPrefixCount));
    importedPackets++;
    followsPacket = true;
  }
  const common = { ...native, messages, meta: { ...native.meta, ownedHistory: {
    conversationId, importedPackets, representation: 'logical-conversation',
  } } };
  assertComplete(common);
  const digest = fingerprint(common);
  if (digest !== prefixFingerprint.digest()) throw new Error('Owned Claude history changed during prefix verification.');
  return { common, digest, importedPackets };
}

export function decodeOwnedClaudeHistory(options) {
  return ownedClaudeHistory(options, packetDecoder(options));
}

/** Select and decode the complete prefix of one already stable snapshot. Share
 * authenticated packet decoding across boundary, reset, sidecar, and history
 * checks without bypassing any of those independent provenance checks.
 */
export function decodeCompletedOwnedClaudeHistory(options) {
  const decodePacket = packetDecoder(options);
  const prefix = completedPrefix(options, decodePacket);
  return { ...ownedClaudeHistory({ ...options, text: prefix.text }, decodePacket, prefix.validated), incompleteTail: prefix.incompleteTail };
}
